"""Writes the public suffix list the release pins (``tld``) as the TypeScript module Node's allowed-website rules read.

Python judges a site by ``tld`` (``app.harness.flow_destination.registrable_domain``); Node refuses a wildcard such as
``*.co.uk`` or ``*.github.io`` at the admin's save (WP-63) by the same list, so the two can never disagree about what
a site is. ``tests/unit/harness/test_wp63_public_suffixes.py`` fails when the committed module is not what this writes.

Run: ``python -m app.scripts.public_suffixes_ts`` (from ``backend/python``).
"""

from __future__ import annotations

from pathlib import Path

import tld

OUTPUT = (
    Path(__file__).resolve().parents[3]
    / "nodejs/apps/src/modules/control-plane/domain/generated/public-suffixes.ts"
)
_HEADER = (
    "// generated by backend/python/app/scripts/public_suffixes_ts.py from the public suffix list of the pinned `tld`"
    " package -- do not edit\n"
    "// Mozilla Public License 2.0: https://publicsuffix.org/list/public_suffix_list.dat\n"
)


def _ascii(rule: str) -> str | None:
    """A rule in the form a host is matched in (IDNA labels); ``None`` for one that has none."""
    prefix = "!" if rule.startswith("!") else ""
    body = rule[1:] if prefix else rule
    labels: list[str] = []
    for label in body.split("."):
        if label == "*" or label.isascii():
            labels.append(label.lower())
            continue
        try:
            labels.append(label.encode("idna").decode("ascii"))
        except UnicodeError:
            return None
    return prefix + ".".join(labels)


def rules() -> list[str]:
    source = Path(tld.__file__).parent / "res" / "effective_tld_names.dat.txt"
    found: set[str] = set()
    for line in source.read_text(encoding="utf-8").splitlines():
        text = line.strip().split(" ", 1)[0]
        if not text or text.startswith("//"):
            continue
        converted = _ascii(text)
        if converted is not None:
            found.add(converted)
    return sorted(found)


def module() -> str:
    body = "\n".join(rules())
    return (
        _HEADER
        + "\n/** The public suffix rules, one per line: `*.` a wildcard rule, `!` an exception (publicsuffix.org). */\n"
        + f"export const PUBLIC_SUFFIX_RULES = `{body}`;\n"
    )


def main() -> None:
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(module(), encoding="utf-8")


if __name__ == "__main__":
    main()
